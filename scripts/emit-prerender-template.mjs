/**
 * Emits the built HTML shell as a JS module so the Vercel prerender function can
 * import it reliably.
 *
 * Vercel bundles files into a serverless function using STATIC analysis of
 * imports/require/fs usage. A dynamic fs.readFileSync of dist/index.html is not
 * detected and the file gets left out in production. By writing the shell into
 * api/_lib/index-template.js (a real ESM module the function imports), the
 * bundler always includes it.
 *
 * Runs after `vite build` (see package.json build script).
 */

import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const BUILT_HTML = path.join(ROOT, "dist", "index.html");
const OUT = path.join(ROOT, "api", "_lib", "index-template.js");

const main = async () => {
  let html;
  try {
    html = await fs.readFile(BUILT_HTML, "utf8");
  } catch {
    console.warn(`[prerender-template] ${BUILT_HTML} not found; skipping (run after vite build).`);
    return;
  }

  const module = `// AUTO-GENERATED by scripts/emit-prerender-template.mjs after \`vite build\`.
// Do not edit by hand. Contains the built index.html shell as a string so the
// Vercel prerender function can import it (static analysis includes this file).
/* eslint-disable */
export const INDEX_TEMPLATE = ${JSON.stringify(html)};
`;

  await fs.mkdir(path.dirname(OUT), { recursive: true });
  await fs.writeFile(OUT, module, "utf8");
  console.log(`[prerender-template] Wrote ${path.relative(ROOT, OUT)} (${html.length} bytes).`);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
